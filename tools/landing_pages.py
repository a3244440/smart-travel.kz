def block(b):
    kind, val = b
    if kind == "p": return f"<p class=\"lp-p\">{val}</p>"
    if kind == "list": return "<ul class=\"lp-list\">" + "".join(f"<li>{x}</li>" for x in val) + "</ul>"
    if kind == "cards": return "<div class=\"values lp-cards\">" + "".join(f"<div class=\"card\"><h3>{e(t)}</h3><p>{d}</p></div>" for t, d in val) + "</div>"
    if kind == "steps": return "<ol class=\"lp-steps\">" + "".join(f"<li><b>{e(t)}</b><span>{d}</span></li>" for t, d in val) + "</ol>"
    raise ValueError(kind)

